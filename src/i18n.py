def t(lang: str, key: str, **kwargs: Any) -> str:
    """Fetch localized UI string cleanly, falling back to English if missing."""
    code = "tr" if str(lang).lower() == "tr" else "en"
    text = TRANSLATIONS.get(code, TRANSLATIONS["en"]).get(key) or TRANSLATIONS["en"].get(key, key)
    if kwargs:
        try:
            return text.format(**kwargs)
        except Exception:
            return text
    return text


def get_scenario_label(scenario_id: str, lang: str, fallback_en: str) -> str:
    if str(lang).lower() == "tr" and scenario_id in SCENARIO_LABELS_TR:
        return SCENARIO_LABELS_TR[scenario_id]
    return fallback_en


def localize_zone(zone: str, lang: str) -> str:
    if str(lang).lower() != "tr":
        return zone
    mapping = {
        "Zone A (Good)": "Bölge A (İyi)",
        "Zone B (GMP Acceptable)": "Bölge B (GMP Uygun)",
        "Zone C (Alert)": "Bölge C (Uyarı)",
        "Zone D (Danger)": "Bölge D (Tehlike)",
    }
    return mapping.get(zone, zone)
